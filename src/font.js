const CHAR_WIDTH = 5;
const CHAR_HEIGHT = 7;

export function drawText(ctx, text, x, y, color = '#ffffff', scale = 1) {
  ctx.fillStyle = color;
  const str = text.toUpperCase();
  for (let i = 0; i < str.length; i++) {
    const charData = FONT_DATA[str[i]];
    if (!charData) continue;
    const cx = x + i * (CHAR_WIDTH + 1) * scale;
    for (let row = 0; row < CHAR_HEIGHT; row++) {
      for (let col = 0; col < CHAR_WIDTH; col++) {
        if (charData[row] & (1 << (CHAR_WIDTH - 1 - col))) {
          ctx.fillRect(
            cx + col * scale,
            y + row * scale,
            scale,
            scale
          );
        }
      }
    }
  }
}

export function measureText(text, scale = 1) {
  return {
    width: text.length * (CHAR_WIDTH + 1) * scale - scale,
    height: CHAR_HEIGHT * scale,
  };
}

export function drawTextCentered(ctx, text, cx, y, color = '#ffffff', scale = 1) {
  const { width } = measureText(text, scale);
  drawText(ctx, text, Math.floor(cx - width / 2), y, color, scale);
}
